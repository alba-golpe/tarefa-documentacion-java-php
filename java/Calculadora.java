/**
 * Clase que realiza operacións matemáticas básicas.
 */
public class Calculadora {

    /**
     * Suma dous valores enteiros.
     *
     * @param a primeiro número
     * @param b segundo número
     * @return suma de a e b
     */
    public int sumar(int a, int b) {
        return a + b;
    }
}
